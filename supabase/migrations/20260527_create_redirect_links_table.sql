create table if not exists public.redirect_links (
  id bigint generated by default as identity primary key,
  code text not null unique,
  target_url text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint redirect_links_code_format check (code ~ '^[a-z0-9][a-z0-9_-]{1,63}$'),
  constraint redirect_links_target_url_protocol check (target_url ~* '^https?://')
);

create index if not exists redirect_links_is_active_idx
  on public.redirect_links (is_active);

create or replace function public.set_redirect_links_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists trg_redirect_links_set_updated_at on public.redirect_links;

create trigger trg_redirect_links_set_updated_at
before update on public.redirect_links
for each row
execute function public.set_redirect_links_updated_at();

alter table public.redirect_links enable row level security;
